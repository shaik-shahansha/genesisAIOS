/**
 * Returns a Blob with the correct minimal structure for the given office extension.
 * Returns null for non-office extensions.
 */
export async function createOfficeTemplate(ext) {
  switch (ext.toLowerCase()) {
    case 'docx': return new Blob([await createBlankDocx()], { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' });
    case 'xlsx': return new Blob([await createBlankXlsx()], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
    case 'pptx': return new Blob([await createBlankPptx()], { type: 'application/vnd.openxmlformats-officedocument.presentationml.presentation' });
    default: return null;
  }
}
